CREATE TABLE IF NOT EXISTS livros (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 titulo VARCHAR(200) NOT NULL,
 autor VARCHAR(150) NOT NULL,
 isbn VARCHAR(30) NOT NULL UNIQUE,
 total INTEGER NOT NULL CHECK(total > 0),
 disponiveis INTEGER NOT NULL CHECK(disponiveis >= 0 AND disponiveis <= total)
);
CREATE TABLE IF NOT EXISTS leitores (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(150) NOT NULL,
 email VARCHAR(200) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS emprestimos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 livro_id BIGINT NOT NULL REFERENCES livros(id),
 leitor_id BIGINT NOT NULL REFERENCES leitores(id),
 realizado_em DATE NOT NULL,
 previsto_em DATE NOT NULL,
 devolvido_em DATE,
 CHECK(previsto_em >= realizado_em),
 CHECK(devolvido_em IS NULL OR devolvido_em >= realizado_em)
);
CREATE INDEX IF NOT EXISTS idx_emprestimos_leitor ON emprestimos(leitor_id);
CREATE INDEX IF NOT EXISTS idx_emprestimos_livro ON emprestimos(livro_id);

